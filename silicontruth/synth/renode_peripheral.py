"""T-084/T-085/T-086 — verified PeripheralIR -> a Renode PythonPeripheral model.

This is the other half of invariant #2. The generated C driver is not trusted
because it compiles; it is trusted because it runs against *this* model and the
model does not complain.

The model encodes three things the datasheet states and a naive driver ignores:

  * the register map, so an access to an undefined offset is an error rather
    than a silently-absorbed write
  * the state machine -- a config register written before its clock-enable bit
    is set, or while a lock bit is active, raises InvalidStateAccess
  * the errata rules -- a missing mandatory delay or dummy read raises
    ErrataViolation

Renode's PythonPeripheral exposes `request` with isInit / isRead / isWrite,
plus `value` and `offset`. We emit a peripheral that logs every transaction in
a line format the oracle parses back (see renode_oracle.MMIO_LINE).
"""

from __future__ import annotations

from silicontruth.ir.schema import ErrataConstraint, PeripheralIR

# The oracle parses this exact shape. Changing it means changing MMIO_LINE too.
TRACE_PREFIX = "SILICONTRUTH_MMIO"


def emit_peripheral(ir: PeripheralIR) -> str:
    """Render a Renode PythonPeripheral for the verified registers."""
    verified = ir.verified_registers
    if not verified:
        raise ValueError(f"{ir.chip}/{ir.peripheral}: no verified registers to model")

    offsets = {r.offset: r for r in sorted(verified, key=lambda r: r.offset)}
    names = {r.offset: r.name for r in verified}
    resets = {r.offset: r.reset_value for r in verified}

    # Which errata the model must police at runtime.
    clock_rules = [
        e for e in ir.errata if e.constraint is ErrataConstraint.CLOCK_ENABLE_BEFORE_ACCESS
    ]
    delay_rules = [
        e for e in ir.errata if e.constraint is ErrataConstraint.DELAY_CYCLES_AFTER_WRITE
    ]
    dummy_rules = [
        e for e in ir.errata if e.constraint is ErrataConstraint.DUMMY_READ_REQUIRED
    ]
    avoid_rules = [e for e in ir.errata if e.constraint is ErrataConstraint.AVOID_VALUE]
    order_rules = [
        e for e in ir.errata if e.constraint is ErrataConstraint.WRITE_ORDER_DEPENDENCY
    ]

    name_to_offset = {r.name: r.offset for r in verified}

    lines: list[str] = [
        f'# {ir.chip} {ir.peripheral} -- Renode PythonPeripheral generated by SiliconTruth.',
        "#",
        "# Encodes the datasheet's register map, state machine and errata traps.",
        "# A driver that violates any of them halts here with a faulting PC,",
        "# which is the signal the repair loop consumes.",
        "",
        "REGISTERS = {",
    ]
    for off, reg in offsets.items():
        lines.append(f"    0x{off:02X}: {{'name': '{reg.name}', 'reset': 0x{reg.reset_value:X}, "
                     f"'width': {reg.width}}},")
    lines += [
        "}",
        "",
        f"CLOCK_GATE_OFFSETS = {sorted({name_to_offset[e.affected_register] for e in clock_rules if e.affected_register in name_to_offset})}",
        f"DELAY_REQUIRED     = {sorted({name_to_offset[e.affected_register] for e in delay_rules if e.affected_register in name_to_offset})}",
        f"DUMMY_READ_AFTER   = {sorted({name_to_offset[e.affected_register] for e in dummy_rules if e.affected_register in name_to_offset})}",
        "FORBIDDEN_VALUES   = {"
        + ", ".join(
            f"0x{name_to_offset[e.affected_register]:02X}: {int(e.params.get('value', 0))}"
            for e in avoid_rules
            if e.affected_register in name_to_offset
        )
        + "}",
        "WRITE_ORDER        = {"
        + ", ".join(
            f"0x{name_to_offset[e.affected_register]:02X}: 0x{name_to_offset[str(e.params.get('must_follow'))]:02X}"
            for e in order_rules
            if e.affected_register in name_to_offset
            and str(e.params.get("must_follow")) in name_to_offset
        )
        + "}",
        "",
        "state = {",
        "    'values': {off: r['reset'] for off, r in REGISTERS.items()},",
        "    'clock_enabled': not CLOCK_GATE_OFFSETS,",
        "    'written': [],",
        "    'last_write': None,",
        "    'cycles_since_write': 0,",
        "}",
        "",
        "",
        "class InvalidStateAccess(Exception):",
        "    pass",
        "",
        "",
        "class ErrataViolation(Exception):",
        "    pass",
        "",
        "",
        "def _log(kind, offset, value, verdict, note=''):",
        f"    name = REGISTERS.get(offset, {{}}).get('name', '?')",
        f"    print('{TRACE_PREFIX} %s 0x%08X %s 0x%08X [%s]%s' %",
        "          (kind, offset, name, value, verdict, (' ' + note) if note else ''))",
        "",
        "",
        "def _check_known(offset):",
        "    if offset not in REGISTERS:",
        "        _log('READ', offset, 0, 'FAIL', 'UNDEFINED_OFFSET')",
        "        raise InvalidStateAccess('access to undefined offset 0x%X' % offset)",
        "",
        "",
        "def _check_clock(offset):",
        "    if CLOCK_GATE_OFFSETS and not state['clock_enabled']:",
        "        if offset not in CLOCK_GATE_OFFSETS:",
        "            _log('WRITE', offset, 0, 'FAIL', 'CLOCK_NOT_ENABLED')",
        "            raise InvalidStateAccess(",
        "                'write to 0x%X before the peripheral clock was enabled' % offset)",
        "",
        "",
        "def _check_errata(offset, value):",
        "    prev = state['last_write']",
        "    if prev is not None and prev in DELAY_REQUIRED and state['cycles_since_write'] < 3:",
        "        _log('WRITE', offset, value, 'FAIL', 'ERRATA_DELAY_MISSING')",
        "        raise ErrataViolation(",
        "            'write to 0x%X only %d cycles after 0x%X; errata requires 3'",
        "            % (offset, state['cycles_since_write'], prev))",
        "    if prev is not None and prev in DUMMY_READ_AFTER and offset != prev:",
        "        _log('WRITE', offset, value, 'FAIL', 'ERRATA_DUMMY_READ_MISSING')",
        "        raise ErrataViolation('errata requires a dummy read of 0x%X' % prev)",
        "    if offset in FORBIDDEN_VALUES and value == FORBIDDEN_VALUES[offset]:",
        "        _log('WRITE', offset, value, 'FAIL', 'ERRATA_FORBIDDEN_VALUE')",
        "        raise ErrataViolation('value 0x%X is forbidden for 0x%X' % (value, offset))",
        "    required = WRITE_ORDER.get(offset)",
        "    if required is not None and required not in state['written']:",
        "        _log('WRITE', offset, value, 'FAIL', 'ERRATA_WRITE_ORDER')",
        "        raise ErrataViolation(",
        "            '0x%X must be written only after 0x%X' % (offset, required))",
        "",
        "",
        "if request.isInit:",
        "    state['values'] = {off: r['reset'] for off, r in REGISTERS.items()}",
        "    state['clock_enabled'] = not CLOCK_GATE_OFFSETS",
        "    state['written'] = []",
        "    state['last_write'] = None",
        "",
        "elif request.isRead:",
        "    _check_known(request.offset)",
        "    request.value = state['values'][request.offset]",
        "    state['cycles_since_write'] += 1",
        "    if state['last_write'] == request.offset:",
        "        state['last_write'] = None  # a dummy read satisfies the errata",
        "    _log('READ', request.offset, request.value, 'PASS')",
        "",
        "elif request.isWrite:",
        "    _check_known(request.offset)",
        "    _check_clock(request.offset)",
        "    _check_errata(request.offset, request.value)",
        "    state['values'][request.offset] = request.value",
        "    state['written'].append(request.offset)",
        "    state['last_write'] = request.offset",
        "    state['cycles_since_write'] = 0",
        "    if request.offset in CLOCK_GATE_OFFSETS:",
        "        state['clock_enabled'] = True",
        "    _log('WRITE', request.offset, request.value, 'PASS')",
        "",
    ]
    return "\n".join(lines)


def emit_repl(ir: PeripheralIR, *, peripheral_file: str = "peripheral_mock.py") -> str:
    """Renode platform description wiring the mock onto the system bus."""
    span = max((r.offset + r.width // 8) for r in ir.verified_registers)
    size = max(0x100, 1 << (span - 1).bit_length())
    return (
        f"// {ir.chip} {ir.peripheral} platform, generated by SiliconTruth\n"
        "cpu: CPU.CortexM @ sysbus\n"
        "    cpuType: \"cortex-m4\"\n"
        "    nvic: nvic\n"
        "\n"
        "nvic: IRQControllers.NVIC @ sysbus 0xE000E000\n"
        "    -> cpu@0\n"
        "\n"
        "mem: Memory.MappedMemory @ sysbus 0x08000000\n"
        "    size: 0x00100000\n"
        "\n"
        "sram: Memory.MappedMemory @ sysbus 0x20000000\n"
        "    size: 0x00020000\n"
        "\n"
        f"{ir.peripheral.lower()}: Python.PythonPeripheral @ sysbus 0x{ir.base_address:08X}\n"
        f"    size: 0x{size:X}\n"
        "    initable: true\n"
        f"    filename: \"{peripheral_file}\"\n"
    )


def emit_resc(ir: PeripheralIR, *, elf: str = "test_firmware.elf", repl: str = "platform.repl") -> str:
    """Renode script that boots the firmware headlessly and quits."""
    return (
        f"# {ir.chip} {ir.peripheral} verification run, generated by SiliconTruth\n"
        "mach create \"silicontruth\"\n"
        f"machine LoadPlatformDescription @{repl}\n"
        f"sysbus LoadELF @{elf}\n"
        "cpu PerformanceInMips 1\n"
        "emulation RunFor \"0.01\"\n"
        "quit\n"
    )
