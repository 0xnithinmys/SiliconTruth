"""T-081/T-083 — verified PeripheralIR -> bare-metal C HAL, with errata injected.

WHAT MAKES THIS DIFFERENT FROM AN LLM WRITING C
-----------------------------------------------
Two things, and both are mechanical rather than probabilistic:

1. Only `ir.verified_registers` is emitted. Invariant #1 again.

2. Every ErrataRule becomes real code, with a comment citing the errata ID and
   the page it came from. A naive single-pass driver reads the reference manual,
   does not read the errata sheet, and omits these -- which is precisely what
   trips the Renode state machine in the demo.

Each emitted workaround carries its provenance in a comment, because the first
thing a skeptical embedded engineer does is ask "says who?" and the answer has
to be a page number.
"""

from __future__ import annotations

from dataclasses import dataclass, field

from silicontruth.ir.schema import ErrataConstraint, ErrataRule, PeripheralIR, Register


class HalEmitError(ValueError):
    """The IR cannot be expressed as a C driver."""


@dataclass
class EmittedHal:
    header: str
    source: str
    errata_applied: list[str] = field(default_factory=list)

    @property
    def errata_count(self) -> int:
        return len(self.errata_applied)


def _guard(chip: str, peripheral: str) -> str:
    return f"SILICONTRUTH_{chip}_{peripheral}_H".upper().replace("-", "_").replace(".", "_")


def _reg_type(reg: Register) -> str:
    return {8: "uint8_t", 16: "uint16_t", 32: "uint32_t"}[reg.width]


def _banner(ir: PeripheralIR) -> str:
    return (
        "/*\n"
        f" * {ir.chip} {ir.peripheral} -- generated by SiliconTruth.\n"
        " *\n"
        " * DO NOT EDIT BY HAND. Regenerate from the datasheet.\n"
        " *\n"
        " * Every register offset and bitfield below was proved by a Z3 SMT solver\n"
        " * (no overlapping fields, full bit-width accounting, aligned addresses)\n"
        " * before this file was written, and the initialisation sequence was\n"
        " * executed against a Renode model of this peripheral.\n"
        " *\n"
        f" * Registers: {len(ir.verified_registers)} verified"
        + (
            f", {len(ir.unverified_registers)} EXCLUDED as unverified\n"
            if ir.unverified_registers
            else "\n"
        )
        + f" * Errata applied: {len(ir.errata)}\n"
        " */\n"
    )


def _unverified_warning(ir: PeripheralIR) -> str:
    if not ir.unverified_registers:
        return ""
    lines = [
        "",
        "/* ---------------------------------------------------------------",
        " * WARNING: the following registers could NOT be verified and are",
        " * deliberately absent from this driver. Writing to them from this",
        " * header is not possible by design.",
        " *",
    ]
    for r in ir.unverified_registers:
        lines.append(f" *   {r.name}: {r.unverified_reason or 'unverified'}")
    lines += [" * --------------------------------------------------------------- */", ""]
    return "\n".join(lines)


def emit_header(ir: PeripheralIR) -> str:
    verified = ir.verified_registers
    if not verified:
        raise HalEmitError(
            f"{ir.chip}/{ir.peripheral}: no verified registers. "
            "Run the Z3 audit and the retry loop before emitting a driver."
        )

    g = _guard(ir.chip, ir.peripheral)
    p = ir.peripheral.upper()
    out: list[str] = [_banner(ir), f"#ifndef {g}", f"#define {g}", "", "#include <stdint.h>", ""]
    out.append(_unverified_warning(ir))

    out += [
        f"#define {p}_BASE  (0x{ir.base_address:08X}UL)",
        "",
        "/* Register offsets */",
    ]
    for reg in sorted(verified, key=lambda r: r.offset):
        out.append(f"#define {p}_{reg.name}_OFFSET  (0x{reg.offset:02X}UL)")

    out += ["", "/* Register accessors (volatile: these are memory-mapped) */"]
    for reg in sorted(verified, key=lambda r: r.offset):
        t = _reg_type(reg)
        out.append(
            f"#define {p}_{reg.name}  "
            f"(*(volatile {t} *)({p}_BASE + {p}_{reg.name}_OFFSET))"
        )

    out += ["", "/* Bitfields: mask and shift, computed in Python and proved in Z3 */"]
    for reg in sorted(verified, key=lambda r: r.offset):
        live = [f for f in reg.fields if not f.reserved]
        if not live:
            continue
        out.append(f"\n/* {reg.name} @ +0x{reg.offset:02X} ({reg.width}-bit) */")
        for f in sorted(live, key=lambda x: x.lsb):
            desc = f" /* {f.description} */" if f.description else ""
            out.append(f"#define {p}_{reg.name}_{f.name}_SHIFT  ({f.lsb}U)")
            out.append(f"#define {p}_{reg.name}_{f.name}_MASK   (0x{f.mask:08X}UL){desc}")

    hooks = _clock_hooks(ir)
    if hooks:
        out += [
            "",
            "/* Board hooks you must implement.",
            " *",
            " * A clock-enable erratum requires a register in ANOTHER peripheral",
            " * (typically RCC) that is not described by this IR and was therefore",
            " * never verified here. This generator will not invent it. Implement",
            " * the hook for your board; leaving it out is a link error, which is",
            " * the loudest failure available and far better than a driver that",
            " * silently accesses an unclocked peripheral. */",
        ]
        for h in hooks:
            out.append(f"int {h}(void);")

    setter_decls, _ = _emit_guarded_setters(ir)
    if setter_decls:
        out += ["", "/* Erratum-guarded write paths. */"]
        out += setter_decls

    out += [
        "",
        "/* Initialise the peripheral. Returns 0 on success. */",
        f"int {ir.peripheral.lower()}_init(void);",
        "",
        f"#endif /* {g} */",
        "",
    ]
    return "\n".join(out)


