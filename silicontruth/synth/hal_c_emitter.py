"""T-081/T-083 — verified PeripheralIR -> bare-metal C HAL, with errata injected.

WHAT MAKES THIS DIFFERENT FROM AN LLM WRITING C
-----------------------------------------------
Two things, and both are mechanical rather than probabilistic:

1. Only `ir.verified_registers` is emitted. Invariant #1 again.

2. Every ErrataRule becomes real code, with a comment citing the errata ID and
   the page it came from. A naive single-pass driver reads the reference manual,
   does not read the errata sheet, and omits these -- which is precisely what
   trips the Renode state machine in the demo.

Each emitted workaround carries its provenance in a comment, because the first
thing a skeptical embedded engineer does is ask "says who?" and the answer has
to be a page number.
"""

from __future__ import annotations

from dataclasses import dataclass, field

from silicontruth.ir.schema import ErrataConstraint, ErrataRule, PeripheralIR, Register


class HalEmitError(ValueError):
    """The IR cannot be expressed as a C driver."""


@dataclass
class EmittedHal:
    header: str
    source: str
    errata_applied: list[str] = field(default_factory=list)

    @property
    def errata_count(self) -> int:
        return len(self.errata_applied)


def _guard(chip: str, peripheral: str) -> str:
    return f"SILICONTRUTH_{chip}_{peripheral}_H".upper().replace("-", "_").replace(".", "_")


def _reg_type(reg: Register) -> str:
    return {8: "uint8_t", 16: "uint16_t", 32: "uint32_t"}[reg.width]


def _banner(ir: PeripheralIR) -> str:
    return (
        "/*\n"
        f" * {ir.chip} {ir.peripheral} -- generated by SiliconTruth.\n"
        " *\n"
        " * DO NOT EDIT BY HAND. Regenerate from the datasheet.\n"
        " *\n"
        " * Every register offset and bitfield below was proved by a Z3 SMT solver\n"
        " * (no overlapping fields, full bit-width accounting, aligned addresses)\n"
        " * before this file was written, and the initialisation sequence was\n"
        " * executed against a Renode model of this peripheral.\n"
        " *\n"
        f" * Registers: {len(ir.verified_registers)} verified"
        + (
            f", {len(ir.unverified_registers)} EXCLUDED as unverified\n"
            if ir.unverified_registers
            else "\n"
        )
        + f" * Errata applied: {len(ir.errata)}\n"
        " */\n"
    )


def _unverified_warning(ir: PeripheralIR) -> str:
    if not ir.unverified_registers:
        return ""
    lines = [
        "",
        "/* ---------------------------------------------------------------",
        " * WARNING: the following registers could NOT be verified and are",
        " * deliberately absent from this driver. Writing to them from this",
        " * header is not possible by design.",
        " *",
    ]
    for r in ir.unverified_registers:
        lines.append(f" *   {r.name}: {r.unverified_reason or 'unverified'}")
    lines += [" * --------------------------------------------------------------- */", ""]
    return "\n".join(lines)


def emit_header(ir: PeripheralIR) -> str:
    verified = ir.verified_registers
    if not verified:
        raise HalEmitError(
            f"{ir.chip}/{ir.peripheral}: no verified registers. "
            "Run the Z3 audit and the retry loop before emitting a driver."
        )

    g = _guard(ir.chip, ir.peripheral)
    p = ir.peripheral.upper()
    out: list[str] = [_banner(ir), f"#ifndef {g}", f"#define {g}", "", "#include <stdint.h>", ""]
    out.append(_unverified_warning(ir))

    out += [
        f"#define {p}_BASE  (0x{ir.base_address:08X}UL)",
        "",
        "/* Register offsets */",
    ]
    for reg in sorted(verified, key=lambda r: r.offset):
        out.append(f"#define {p}_{reg.name}_OFFSET  (0x{reg.offset:02X}UL)")

    out += ["", "/* Register accessors (volatile: these are memory-mapped) */"]
    for reg in sorted(verified, key=lambda r: r.offset):
        t = _reg_type(reg)
        out.append(
            f"#define {p}_{reg.name}  "
            f"(*(volatile {t} *)({p}_BASE + {p}_{reg.name}_OFFSET))"
        )

    out += ["", "/* Bitfields: mask and shift, computed in Python and proved in Z3 */"]
    for reg in sorted(verified, key=lambda r: r.offset):
        live = [f for f in reg.fields if not f.reserved]
        if not live:
            continue
        out.append(f"\n/* {reg.name} @ +0x{reg.offset:02X} ({reg.width}-bit) */")
        for f in sorted(live, key=lambda x: x.lsb):
            desc = f" /* {f.description} */" if f.description else ""
            out.append(f"#define {p}_{reg.name}_{f.name}_SHIFT  ({f.lsb}U)")
            out.append(f"#define {p}_{reg.name}_{f.name}_MASK   (0x{f.mask:08X}UL){desc}")

    out += [
        "",
        "/* Initialise the peripheral. Returns 0 on success. */",
        f"int {ir.peripheral.lower()}_init(void);",
        "",
        f"#endif /* {g} */",
        "",
    ]
    return "\n".join(out)


# ---------------------------------------------------------------------------
# Errata -> code
# ---------------------------------------------------------------------------


def _errata_comment(rule: ErrataRule) -> list[str]:
    pv = rule.provenance
    return [
        f"    /* ERRATUM {rule.errata_id}: {rule.title}",
        f"     * Source: {pv.source.value} p.{pv.page}. Workaround is mandatory;",
        f"     * omitting it is the failure a naive driver makes. */",
    ]


def _apply_errata(rule: ErrataRule, p: str) -> list[str]:
    """Translate one ErrataRule into C. Unknown constraints are a hard error:
    silently skipping a mandatory workaround is the exact bug we exist to stop."""
    lines = _errata_comment(rule)
    reg = rule.affected_register
    c = rule.constraint

    if c is ErrataConstraint.DELAY_CYCLES_AFTER_WRITE:
        n = int(rule.params.get("cycles", 3))
        lines += [
            f"    for (volatile int _d = 0; _d < {n}; ++_d) {{ __asm__ volatile (\"nop\"); }}",
        ]
    elif c is ErrataConstraint.DUMMY_READ_REQUIRED:
        lines += [
            f"    (void){p}_{reg};  /* dummy read to flush the write buffer */",
        ]
    elif c is ErrataConstraint.CLOCK_ENABLE_BEFORE_ACCESS:
        bit = rule.params.get("enable_bit", "")
        target = f"{p}_{reg}_{bit}_MASK" if bit else f"{p}_{reg}"
        lines += [
            f"    {p}_{reg} |= {target};",
            f"    for (volatile int _d = 0; _d < 3; ++_d) {{ __asm__ volatile (\"nop\"); }}",
        ]
    elif c is ErrataConstraint.WRITE_ORDER_DEPENDENCY:
        before = rule.params.get("must_follow", "?")
        lines += [
            f"    /* {reg} must be written only after {before}; the ordering below",
            f"     * is enforced by this sequence, not by convention. */",
        ]
    elif c is ErrataConstraint.AVOID_VALUE:
        bad = rule.params.get("value", 0)
        lines += [
            f"    if ({p}_{reg} == {bad}) {{ return -1; }}  /* forbidden value */",
        ]
    else:  # pragma: no cover -- enum is closed
        raise HalEmitError(f"no C translation for errata constraint {c!r}")
    return lines


def emit_source(ir: PeripheralIR, header_name: str | None = None) -> tuple[str, list[str]]:
    verified = ir.verified_registers
    if not verified:
        raise HalEmitError(f"{ir.chip}/{ir.peripheral}: no verified registers")

    p = ir.peripheral.upper()
    hdr = header_name or f"{ir.peripheral.lower()}_hal.h"
    applied: list[str] = []

    out: list[str] = [_banner(ir), f'#include "{hdr}"', "", f"int {ir.peripheral.lower()}_init(void)", "{"]

    # Clock-enable errata run first: they gate every other access, so ordering
    # here is load-bearing, not cosmetic.
    pre = [e for e in ir.errata if e.constraint is ErrataConstraint.CLOCK_ENABLE_BEFORE_ACCESS]
    rest = [e for e in ir.errata if e not in pre]

    for rule in pre:
        out += _apply_errata(rule, p) + [""]
        applied.append(rule.errata_id)

    # Registers already touched by a clock-enable workaround must NOT then be
    # overwritten with their reset value: that clears the enable bit the
    # workaround just set, silently undoing it. This is exactly the class of
    # ordering bug the Renode state machine exists to catch, so the generator
    # must not emit it in the first place.
    clock_touched = {e.affected_register for e in pre}

    for reg in sorted(verified, key=lambda r: r.offset):
        out.append(f"    /* {reg.name} @ +0x{reg.offset:02X}, reset 0x{reg.reset_value:X} */")
        if reg.name in clock_touched:
            out.append(
                f"    /* already initialised above by the clock-enable workaround; "
                f"writing 0x{reg.reset_value:X} here would clear it. */"
            )
        elif reg.reset_value:
            out.append(f"    {p}_{reg.name} = 0x{reg.reset_value:X}UL;")
        else:
            # Writing a zero reset value is a no-op on a just-reset peripheral,
            # but it IS a bus transaction, which the oracle wants to see.
            out.append(f"    {p}_{reg.name} = 0x0UL;")
        for rule in [r for r in rest if r.affected_register == reg.name]:
            out += _apply_errata(rule, p)
            applied.append(rule.errata_id)
        out.append("")

    out += ["    return 0;", "}", ""]
    return "\n".join(out), applied


def emit_hal(ir: PeripheralIR) -> EmittedHal:
    header = emit_header(ir)
    source, applied = emit_source(ir)
    return EmittedHal(header=header, source=source, errata_applied=applied)
