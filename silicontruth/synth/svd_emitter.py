"""T-075 — verified PeripheralIR -> CMSIS-SVD XML.

Only `ir.verified_registers` is ever emitted. A register that failed the Z3 gate
cannot reach this file, because the emitter does not look at the full list. That
is the enforcement point for invariant #1: no unproved output reaches codegen.

The ARM CMSIS-SVD schema is specific about ordering and representation:
  - element order inside <device>, <peripheral> and <register> is fixed
  - numeric literals are hex with a 0x prefix
  - <bitRange> is written "[msb:lsb]"
  - names must be valid C identifiers, because svd2rust and the CMSIS headers
    turn them into symbols directly

We emit with xml.etree (stdlib) and validate structurally in `validate_svd`.
Full XSD validation happens in the Modal container (T-076) where the schema and
`svdtools` are installed; this module enforces the rules that break svd2rust.
"""

from __future__ import annotations

import re
import xml.etree.ElementTree as ET
from dataclasses import dataclass
from xml.dom import minidom

from silicontruth.ir.schema import Access, PeripheralIR, Register

# CMSIS-SVD access vocabulary. Our IR uses the same words plus the
# modified-write variants, which SVD expresses separately.
_ACCESS_MAP: dict[str, str] = {
    "rw": "read-write",
    "ro": "read-only",
    "wo": "write-only",
    "rc_w0": "read-write",
    "rc_w1": "read-write",
    "w1c": "read-write",
}

# The modified-write semantics SVD carries alongside <access>.
_MODIFIED_WRITE: dict[str, str] = {
    "rc_w0": "zeroToClear",
    "rc_w1": "oneToClear",
    "w1c": "oneToClear",
}

_C_IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


class SvdEmitError(ValueError):
    """The IR cannot be expressed as valid SVD."""


@dataclass(frozen=True)
class SvdValidation:
    ok: bool
    errors: tuple[str, ...] = ()

    def __bool__(self) -> bool:
        return self.ok


def _hex(value: int) -> str:
    return f"0x{value:X}"


def _sub(parent: ET.Element, tag: str, text: str) -> ET.Element:
    el = ET.SubElement(parent, tag)
    el.text = text
    return el


def _check_ident(name: str, what: str) -> None:
    if not _C_IDENT.match(name):
        raise SvdEmitError(
            f"{what} {name!r} is not a valid C identifier; svd2rust and the "
            "generated CMSIS headers turn this straight into a symbol"
        )


def _register_size(reg: Register) -> int:
    return reg.width


def _emit_fields(reg_el: ET.Element, reg: Register) -> None:
    # Reserved fields are deliberately NOT emitted. SVD treats undeclared bits as
    # reserved, and svd2rust warns on explicit reserved fields. They still count
    # in the Z3 width-conservation proof, which is where they matter.
    live = [f for f in reg.fields if not f.reserved]
    if not live:
        return
    fields_el = ET.SubElement(reg_el, "fields")
    for f in sorted(live, key=lambda x: x.lsb):
        _check_ident(f.name, "field name")
        fel = ET.SubElement(fields_el, "field")
        _sub(fel, "name", f.name)
        if f.description:
            _sub(fel, "description", f.description)
        _sub(fel, "bitRange", f"[{f.msb}:{f.lsb}]")
        _sub(fel, "access", _ACCESS_MAP[f.access])
        mw = _MODIFIED_WRITE.get(f.access)
        if mw:
            _sub(fel, "modifiedWriteValues", mw)


def emit_svd(ir: PeripheralIR, *, vendor: str = "", description: str = "") -> str:
    """Render verified registers as a CMSIS-SVD document.

    Raises SvdEmitError if nothing is verified -- emitting an empty device would
    silently produce a driver with no registers, which is worse than failing.
    """
    verified = ir.verified_registers
    if not verified:
        raise SvdEmitError(
            f"{ir.chip}/{ir.peripheral}: no verified registers to emit. "
            f"{len(ir.unverified_registers)} register(s) failed the Z3 gate. "
            "Run the audit and the retry loop before emitting."
        )

    _check_ident(ir.peripheral, "peripheral name")

    dev = ET.Element("device", {"schemaVersion": "1.3"})
    _sub(dev, "vendor", vendor or "Unknown")
    _sub(dev, "name", re.sub(r"[^A-Za-z0-9_]", "_", ir.chip))
    _sub(dev, "version", "1.0")
    _sub(dev, "description", description or f"{ir.chip} {ir.peripheral}, generated by SiliconTruth")
    _sub(dev, "addressUnitBits", "8")
    _sub(dev, "width", "32")
    _sub(dev, "size", "32")
    _sub(dev, "access", "read-write")
    _sub(dev, "resetValue", "0x0")
    _sub(dev, "resetMask", "0xFFFFFFFF")

    periphs = ET.SubElement(dev, "peripherals")
    per = ET.SubElement(periphs, "peripheral")
    _sub(per, "name", ir.peripheral)
    _sub(per, "description", f"{ir.peripheral} peripheral")
    _sub(per, "baseAddress", _hex(ir.base_address))

    block = ET.SubElement(per, "addressBlock")
    span = max((r.offset + r.width // 8) for r in verified)
    _sub(block, "offset", "0x0")
    _sub(block, "size", _hex(span))
    _sub(block, "usage", "registers")

    regs_el = ET.SubElement(per, "registers")
    for reg in sorted(verified, key=lambda r: r.offset):
        _check_ident(reg.name, "register name")
        rel = ET.SubElement(regs_el, "register")
        _sub(rel, "name", reg.name)
        _sub(rel, "displayName", reg.name)
        _sub(rel, "addressOffset", _hex(reg.offset))
        _sub(rel, "size", str(_register_size(reg)))
        _sub(rel, "access", _ACCESS_MAP[reg.access])
        _sub(rel, "resetValue", _hex(reg.reset_value))
        _emit_fields(rel, reg)

    raw = ET.tostring(dev, encoding="unicode")
    pretty = minidom.parseString(raw).toprettyxml(indent="  ")
    # minidom emits a bare declaration; SVD files conventionally carry encoding.
    body = "\n".join(line for line in pretty.splitlines()[1:] if line.strip())
    return '<?xml version="1.0" encoding="utf-8"?>\n' + body + "\n"


def validate_svd(xml_text: str) -> SvdValidation:
    """Structural validation of the rules that actually break svd2rust.

    Not a substitute for XSD validation in the Modal container, but it catches
    everything we can generate wrong, and it runs with no network and no schema file.
    """
    errors: list[str] = []
    try:
        root = ET.fromstring(xml_text)
    except ET.ParseError as e:
        return SvdValidation(False, (f"not well-formed XML: {e}",))

    if root.tag != "device":
        errors.append(f"root element is <{root.tag}>, expected <device>")

    for required in ("name", "version", "addressUnitBits", "width", "peripherals"):
        if root.find(required) is None:
            errors.append(f"<device> is missing required child <{required}>")

    seen_offsets: dict[str, set[int]] = {}
    for per in root.iter("peripheral"):
        pname_el = per.find("name")
        pname = pname_el.text if pname_el is not None and pname_el.text else "?"
        if per.find("baseAddress") is None:
            errors.append(f"peripheral {pname}: missing <baseAddress>")
        seen_offsets.setdefault(pname, set())

        for reg in per.iter("register"):
            rn_el = reg.find("name")
            rn = rn_el.text if rn_el is not None and rn_el.text else "?"
            if rn != "?" and not _C_IDENT.match(rn):
                errors.append(f"register {rn!r}: not a valid C identifier")

            off_el = reg.find("addressOffset")
            if off_el is None or not off_el.text:
                errors.append(f"register {rn}: missing <addressOffset>")
            else:
                try:
                    off = int(off_el.text, 0)
                except ValueError:
                    errors.append(f"register {rn}: addressOffset {off_el.text!r} is not numeric")
                else:
                    if off in seen_offsets[pname]:
                        errors.append(f"register {rn}: duplicate addressOffset {off_el.text}")
                    seen_offsets[pname].add(off)

            size_el = reg.find("size")
            size = int(size_el.text) if size_el is not None and size_el.text else 32

            # Bit ranges must parse, sit inside the register, and not overlap.
            covered = 0
            for fld in reg.iter("field"):
                fn_el = fld.find("name")
                fn = fn_el.text if fn_el is not None and fn_el.text else "?"
                br = fld.find("bitRange")
                if br is None or not br.text:
                    errors.append(f"{rn}.{fn}: missing <bitRange>")
                    continue
                m = re.fullmatch(r"\[(\d+):(\d+)\]", br.text.strip())
                if not m:
                    errors.append(f"{rn}.{fn}: bitRange {br.text!r} is not '[msb:lsb]'")
                    continue
                msb, lsb = int(m.group(1)), int(m.group(2))
                if lsb > msb:
                    errors.append(f"{rn}.{fn}: bitRange [{msb}:{lsb}] has lsb > msb")
                    continue
                if msb >= size:
                    errors.append(f"{rn}.{fn}: bit {msb} exceeds {size}-bit register")
                    continue
                mask = ((1 << (msb - lsb + 1)) - 1) << lsb
                if mask & covered:
                    errors.append(f"{rn}.{fn}: bitRange [{msb}:{lsb}] overlaps another field")
                covered |= mask

    return SvdValidation(not errors, tuple(errors))
