"""The firmware that actually exercises the generated driver.

This closes a hole in invariant #2. `emit_resc` has always written
`sysbus LoadELF @test_firmware.elf`, and nothing in the repo produced that
ELF: there was no startup code, no linker script, and the compile step passed
`-c`, so it only ever made object files. The emulation gate could not have run
even with Renode installed, because there was nothing to load.

What is emitted here is deliberately minimal and deliberately NOT generated by
a model:

  * a vector table with an initial stack pointer and a reset handler, which is
    the smallest thing a Cortex-M will boot
  * a linker script placing .text in the flash region and the stack at the top
    of the SRAM region, both of which the generated platform.repl declares
  * `main`, which calls the driver's init and then parks

and one board hook. The generated HAL declares `<peripheral>_enable_clock()`
without defining it, on purpose: the clock-enable bit lives in another
peripheral that this IR never described, and the generator refuses to invent
it. That makes an unimplemented hook a link error. The test firmware is the
board, so the test firmware is what implements it.

The hook's implementation is the one judgement call in this file. The Renode
model treats the registers named in CLOCK_GATE_OFFSETS as the gate, so the
hook writes the first of them. On real silicon it would be an RCC write. Both
are a write that must precede any other access, which is the property under
test.
"""

from __future__ import annotations

from silicontruth.ir.schema import ErrataConstraint, PeripheralIR

# Matches the regions emit_repl declares. Kept here as named constants rather
# than inline, because a linker script that disagrees with platform.repl by one
# digit produces a firmware that loads and immediately hard-faults, which is a
# miserable thing to debug.
FLASH_ORIGIN = 0x0800_0000
FLASH_LENGTH = 0x0010_0000
SRAM_ORIGIN = 0x2000_0000
SRAM_LENGTH = 0x0002_0000


def emit_linker_script() -> str:
    """Place the image where platform.repl says memory is."""
    return f"""/* Generated by SiliconTruth. Regions match platform.repl. */
MEMORY
{{
  FLASH (rx)  : ORIGIN = 0x{FLASH_ORIGIN:08X}, LENGTH = 0x{FLASH_LENGTH:08X}
  SRAM  (rwx) : ORIGIN = 0x{SRAM_ORIGIN:08X}, LENGTH = 0x{SRAM_LENGTH:08X}
}}

ENTRY(Reset_Handler)

SECTIONS
{{
  .vectors : {{ KEEP(*(.vectors)) }} > FLASH
  .text    : {{ *(.text*) *(.rodata*) }} > FLASH
  .data    : {{ *(.data*) }} > SRAM AT > FLASH
  .bss     : {{ *(.bss*) *(COMMON) }} > SRAM

  _stack_top = ORIGIN(SRAM) + LENGTH(SRAM);
}}
"""


def emit_firmware(ir: PeripheralIR) -> str:
    """The test program: enable the clock, initialise, stop."""
    p = ir.peripheral.lower()
    verified = sorted(ir.verified_registers, key=lambda r: r.offset)
    if not verified:
        raise ValueError(f"{ir.chip}/{ir.peripheral}: no verified registers to exercise")

    needs_clock_hook = any(
        e.constraint is ErrataConstraint.CLOCK_ENABLE_BEFORE_ACCESS for e in ir.errata
    )
    gate = verified[0]

    hook = ""
    if needs_clock_hook:
        hook = f"""
/* The board hook the generated HAL declares and refuses to define.
 *
 * It writes NOTHING, and that is deliberate. On real silicon enabling the
 * clock is a write to a clock controller -- RCC on STM32 -- which is a
 * different peripheral, absent from this IR, at an address no gate here has
 * verified. hal_c_emitter refuses to invent that write; a generated test
 * firmware inventing it instead would defeat the same rule one layer down.
 *
 * An earlier version wrote {ir.peripheral.upper()}_{gate.name} and called that "enabling the
 * clock". It was not: {gate.name} is a register the erratum PROTECTS, so the
 * write both misrepresented the hardware and collided with the delay erratum
 * on that same register. The emulation gate caught it the first time it ran.
 *
 * Satisfying the linker is the whole job here. Whether the clock was actually
 * enabled before the first access is not observable from inside this
 * peripheral's address window, so peripheral_mock.py abstains on it rather
 * than reporting a result it cannot support. */
int {p}_enable_clock(void)
{{
    return 0;
}}
"""

    return f"""/*
 * Test firmware for {ir.chip} {ir.peripheral}, generated by SiliconTruth.
 *
 * Boots on the generated platform, drives the generated driver, and stops.
 * Every bus access it makes is judged by peripheral_mock.py and read back
 * out of the Renode log by the oracle.
 */

#include <stdint.h>

#include "{p}_hal.h"

extern uint32_t _stack_top;

void Reset_Handler(void);
static void park(void);
{hook}
int main(void)
{{
    /* A non-zero return would mean the driver refused to initialise, which
     * the oracle sees as an absent trace rather than a wrong one. */
    if ({p}_init() != 0) {{
        park();
    }}
    park();
    return 0;
}}

static void park(void)
{{
    /* Renode runs for a fixed slice and quits. Spinning here keeps the CPU
     * from wandering into unmapped memory after main returns, which would
     * raise a fault the oracle would correctly report as a failure. */
    for (;;) {{
        __asm__ volatile("nop");
    }}
}}

void Reset_Handler(void)
{{
    main();
    park();
}}

/* Initial SP and reset vector. The Cortex-M core loads both from address 0
 * of the image at power-on, so this must be the first thing in flash. */
__attribute__((section(".vectors"), used))
static void *const vectors[] = {{
    (void *)&_stack_top,
    (void *)Reset_Handler,
}};
"""
