"""Emit a `no_std` Rust HAL from a verified PeripheralIR.

Deliberately NOT a replacement for svd2rust. svd2rust consumes the SVD
this project already emits and produces the peripheral access crate; that
remains the right tool and the SVD remains the interchange format. What
svd2rust cannot produce is the errata layer, because the errata are not in
the SVD -- they are in a different document that the register map has no
vocabulary for.

So this emitter generates the thin layer above a PAC: the verified
constants, and the workarounds expressed as Rust that cannot be bypassed
as easily as a comment can.

The same three rules as the C emitter, for the same reasons:

  * An unverified register reaches no output. The gate decides, not this
    module.
  * A clock-enable erratum whose register lives in another peripheral
    becomes an `extern` function the integrator must provide -- an
    unimplemented workaround is a link error, not a silent omission.
  * An `avoid_value` erratum becomes a setter that refuses the write,
    scoped to the field when the erratum names one.

Rust lets two of those be stronger than in C: the forbidden-value check
returns `Result`, so ignoring it is a `#[must_use]` warning rather than an
ignored int, and every MMIO access is wrapped in exactly one `unsafe`
block with the safety argument written next to it.
"""

from __future__ import annotations

from dataclasses import dataclass

from silicontruth.ir.schema import ErrataConstraint, ErrataRule, PeripheralIR


class RustEmitError(RuntimeError):
    pass


@dataclass(frozen=True)
class EmittedRust:
    source: str
    errata_applied: list[str]

    @property
    def errata_count(self) -> int:
        return len(self.errata_applied)


def _ident(name: str) -> str:
    """Rust constants are SCREAMING_SNAKE; field names from datasheets are
    already close, but may contain characters Rust will not accept."""
    out = "".join(c if c.isalnum() else "_" for c in name).upper()
    return out if out and not out[0].isdigit() else f"F_{out}"


def _snake(name: str) -> str:
    return "".join(c if c.isalnum() else "_" for c in name).lower()


def _banner(ir: PeripheralIR, errata: list[str]) -> list[str]:
    return [
        "//! Generated by SiliconTruth. DO NOT EDIT BY HAND.",
        "//!",
        f"//! {ir.chip} / {ir.peripheral} @ 0x{ir.base_address:08X}",
        "//!",
        "//! Every offset and bitfield below was proved by a Z3 SMT solver",
        "//! (no overlapping fields, full bit-width accounting, aligned",
        "//! addresses) before this file was written.",
        "//!",
        f"//! Registers: {len(ir.verified_registers)} verified"
        + (
            f", {len(ir.unverified_registers)} EXCLUDED as unverified"
            if ir.unverified_registers
            else ""
        ),
        f"//! Errata applied: {len(errata)}"
        + (f" ({', '.join(errata)})" if errata else ""),
        "",
        "#![allow(dead_code)]",
        "",
        "use core::ptr::{read_volatile, write_volatile};",
        "",
    ]


def _unverified_note(ir: PeripheralIR) -> list[str]:
    if not ir.unverified_registers:
        return []
    out = [
        "// The following registers FAILED verification and are deliberately",
        "// absent from this file. They are listed so their absence is a",
        "// documented decision rather than an oversight:",
    ]
    for reg in ir.unverified_registers:
        why = (reg.unverified_reason or "unverified").splitlines()[0][:120]
        out.append(f"//   {reg.name} @ +0x{reg.offset:02X}: {why}")
    return out + [""]


def _accessors(ir: PeripheralIR) -> list[str]:
    p = _snake(ir.peripheral)
    out = [
        f"pub const BASE: usize = 0x{ir.base_address:08X};",
        "",
        "/// Read a register by byte offset.",
        "///",
        "/// # Safety",
        "/// `offset` must be one of the verified offsets in this module. Every",
        "/// such offset was proved 4-byte aligned and within the peripheral's",
        "/// window before this file was generated.",
        "#[inline(always)]",
        "unsafe fn rd(offset: usize) -> u32 {",
        "    read_volatile((BASE + offset) as *const u32)",
        "}",
        "",
        "/// Write a register by byte offset.",
        "///",
        "/// # Safety",
        "/// Same contract as [`rd`].",
        "#[inline(always)]",
        "unsafe fn wr(offset: usize, value: u32) {",
        "    write_volatile((BASE + offset) as *mut u32, value);",
        "}",
        "",
    ]
    del p
    return out


def _constants(ir: PeripheralIR) -> list[str]:
    out: list[str] = []
    for reg in sorted(ir.verified_registers, key=lambda r: r.offset):
        rn = _ident(reg.name)
        out += [
            f"/// {reg.name} @ +0x{reg.offset:02X} ({reg.width}-bit), "
            f"reset 0x{reg.reset_value:08X}",
            f"pub const {rn}_OFFSET: usize = 0x{reg.offset:02X};",
            f"pub const {rn}_RESET: u32 = 0x{reg.reset_value:08X};",
        ]
        live = [f for f in reg.fields if not f.reserved]
        for f in sorted(live, key=lambda x: x.lsb):
            fn = _ident(f.name)
            desc = f"  // {f.description}" if f.description else ""
            out.append(f"pub const {rn}_{fn}_SHIFT: u32 = {f.lsb};")
            out.append(f"pub const {rn}_{fn}_MASK: u32 = 0x{f.mask:08X};{desc}")
        out.append("")
    return out


def _clock_hooks(ir: PeripheralIR) -> list[str]:
    hooks = sorted(
        {
            f"{_snake(ir.peripheral)}_enable_clock"
            for e in ir.errata
            if e.constraint is ErrataConstraint.CLOCK_ENABLE_BEFORE_ACCESS
        }
    )
    if not hooks:
        return []
    out = [
        "// Board hooks you must provide.",
        "//",
        "// A clock-enable erratum requires a register in ANOTHER peripheral",
        "// (typically RCC) that this IR does not describe and Z3 never",
        "// verified. This generator will not invent it. Provide the symbol",
        "// for your board; leaving it out is a link error, which is the",
        "// loudest failure available and far better than a driver that",
        "// silently accesses an unclocked peripheral.",
        'extern "C" {',
    ]
    for h in hooks:
        out.append(f"    pub fn {h}() -> i32;")
    return out + ["}", ""]


def _order_registers(ir: PeripheralIR) -> list:
    """Same topological ordering as the C emitter, and for the same reason:
    a comment claiming the sequence enforces an ordering must be true."""
    regs = sorted(ir.verified_registers, key=lambda r: r.offset)
    names = {r.name for r in regs}
    after: dict[str, set[str]] = {r.name: set() for r in regs}
    for e in ir.errata:
        if e.constraint is not ErrataConstraint.WRITE_ORDER_DEPENDENCY:
            continue
        other = str(e.params.get("other_register", ""))
        if e.affected_register in names and other in names:
            after[e.affected_register].add(other)

    ordered, emitted, remaining = [], set(), list(regs)
    while remaining:
        ready = [r for r in remaining if after[r.name] <= emitted]
        if not ready:
            stuck = ", ".join(sorted(r.name for r in remaining))
            raise RustEmitError(
                f"{ir.chip}/{ir.peripheral}: write-order errata form a cycle "
                f"among [{stuck}]; no write order satisfies them"
            )
        nxt = ready[0]
        ordered.append(nxt)
        emitted.add(nxt.name)
        remaining.remove(nxt)
    return ordered


def _errata_doc(rule: ErrataRule, indent: str = "    ") -> list[str]:
    pv = rule.provenance
    return [
        f"{indent}// ERRATUM {rule.errata_id}: {rule.title}",
        f"{indent}// Source: {pv.source.value} p.{pv.page}. The workaround is",
        f"{indent}// mandatory; omitting it is the failure a naive driver makes.",
    ]


def _errata_in_init(rule: ErrataRule, ir: PeripheralIR) -> list[str]:
    c = rule.constraint
    reg = _ident(rule.affected_register)
    lines = _errata_doc(rule)

    if c is ErrataConstraint.DELAY_CYCLES_AFTER_WRITE:
        n = int(rule.params.get("cycles", 3))
        lines += [
            f"    // {n} cycles, as a real instruction per iteration.",
            "    //",
            "    // NOT compiler_fence: that is a compile-time barrier which emits",
            "    // no instruction at all, so a loop whose body is only a fence has",
            "    // no runtime effect and is removed outright -- silently deleting",
            "    // a mandatory workaround, which is the exact defect class this",
            "    // project exists to prevent. `nop` is a real instruction on both",
            "    // ARM and RISC-V, and asm! is never elided.",
            f"    for _ in 0..{n} {{",
            "        // SAFETY: `nop` has no operands and touches no memory.",
            '        unsafe { core::arch::asm!("nop", options(nomem, nostack)) };',
            "    }",
        ]
    elif c is ErrataConstraint.DUMMY_READ_REQUIRED:
        lines += [
            f"    // SAFETY: {reg}_OFFSET is a verified offset.",
            f"    let _ = unsafe {{ rd({reg}_OFFSET) }};",
        ]
    elif c is ErrataConstraint.CLOCK_ENABLE_BEFORE_ACCESS:
        hook = f"{_snake(ir.peripheral)}_enable_clock"
        lines += [
            "    // SAFETY: calling a board-provided C symbol with no arguments.",
            f"    if unsafe {{ {hook}() }} != 0 {{",
            "        return Err(Error::ClockEnableFailed);",
            "    }",
        ]
    elif c is ErrataConstraint.WRITE_ORDER_DEPENDENCY:
        before = rule.params.get("other_register", "?")
        lines += [
            f"    // {rule.affected_register} is written only after {before}.",
            "    // Enforced by _order_registers() at generation time.",
        ]
    elif c is ErrataConstraint.AVOID_VALUE:
        fld = str(rule.params.get("field", "") or "")
        where = f"{rule.affected_register}.{fld}" if fld else rule.affected_register
        lines += [
            f"    // The forbidden value for {where} is rejected by the",
            "    // generated setter below. init() writes only the reset value,",
            "    // which the erratum does not forbid.",
        ]
    else:  # pragma: no cover - the enum is closed
        raise RustEmitError(f"no Rust translation for {c!r}")
    return lines


def _guarded_setters(ir: PeripheralIR) -> list[str]:
    """`Result`-returning setters that refuse the forbidden write.

    Stronger than the C version: `Result` is `#[must_use]`, so discarding
    the outcome is a compiler warning rather than an ignored return code.
    """
    out: list[str] = []
    by_name = {r.name: r for r in ir.verified_registers}

    for rule in [e for e in ir.errata if e.constraint is ErrataConstraint.AVOID_VALUE]:
        reg = by_name.get(rule.affected_register)
        if reg is None:
            continue
        rn = _ident(reg.name)
        field = str(rule.params.get("field", "") or "")
        bad = rule.params.get("value", 0)
        bad_hex = f"0x{int(bad):X}" if isinstance(bad, int) else str(bad)
        live = {f.name for f in reg.fields if not f.reserved}

        if field and field not in live:
            out += [
                f"// ERRATUM {rule.errata_id} names field `{field}` of {reg.name},",
                "// which is not among this register's verified fields. No setter",
                "// is generated: writing bits no Z3 run verified is the defect",
                "// this tool exists to prevent.",
                "",
            ]
            continue

        name = (
            f"set_{_snake(reg.name)}_{_snake(field)}"
            if field
            else f"set_{_snake(reg.name)}"
        )
        out += _errata_doc(rule, indent="")
        out += [
            f"pub fn {name}(value: u32) -> Result<(), Error> {{",
            f"    if value == {bad_hex} {{",
            f"        return Err(Error::ForbiddenValue {{ errata: \"{rule.errata_id}\" }});",
            "    }",
        ]
        if field:
            fn = _ident(field)
            out += [
                f"    // SAFETY: {rn}_OFFSET is verified, and the mask confines",
                f"    // the write to the {field} field.",
                "    unsafe {",
                f"        let cur = rd({rn}_OFFSET);",
                f"        wr({rn}_OFFSET, (cur & !{rn}_{fn}_MASK)",
                f"            | ((value << {rn}_{fn}_SHIFT) & {rn}_{fn}_MASK));",
                "    }",
            ]
        else:
            out += [
                f"    // SAFETY: {rn}_OFFSET is a verified offset.",
                f"    unsafe {{ wr({rn}_OFFSET, value) }};",
            ]
        out += ["    Ok(())", "}", ""]
    return out


def emit_rust(ir: PeripheralIR) -> EmittedRust:
    verified = ir.verified_registers
    if not verified:
        # The same refusal as every other generator. An IR with nothing
        # verified must produce nothing, not an empty-but-valid module that
        # looks like a successful run.
        raise RustEmitError(f"{ir.chip}/{ir.peripheral}: no verified registers")

    applied: list[str] = []
    pre = [
        e for e in ir.errata
        if e.constraint is ErrataConstraint.CLOCK_ENABLE_BEFORE_ACCESS
    ]
    rest = [e for e in ir.errata if e not in pre]
    ordered = _order_registers(ir)

    body: list[str] = []
    for rule in pre:
        body += _errata_in_init(rule, ir) + [""]
        applied.append(rule.errata_id)

    for reg in ordered:
        rn = _ident(reg.name)
        body.append(f"    // {reg.name} @ +0x{reg.offset:02X}")
        body.append(f"    // SAFETY: {rn}_OFFSET is a verified offset.")
        body.append(f"    unsafe {{ wr({rn}_OFFSET, {rn}_RESET) }};")
        for rule in [r for r in rest if r.affected_register == reg.name]:
            body += _errata_in_init(rule, ir)
            applied.append(rule.errata_id)
        body.append("")

    out: list[str] = []
    out += _banner(ir, applied)
    out += _unverified_note(ir)
    out += [
        "/// Errors this driver can report.",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
        "pub enum Error {",
        "    /// A board-provided clock-enable hook failed.",
        "    ClockEnableFailed,",
        "    /// A write was refused because an erratum forbids that value.",
        "    ForbiddenValue { errata: &'static str },",
        "}",
        "",
    ]
    out += _accessors(ir)
    out += _constants(ir)
    out += _clock_hooks(ir)
    out += [
        "/// Initialise the peripheral.",
        "///",
        "/// Writes each verified register's reset value in an order that",
        "/// satisfies every write-order erratum, applying the mandatory",
        "/// workarounds in place.",
        "pub fn init() -> Result<(), Error> {",
        *body,
        "    Ok(())",
        "}",
        "",
    ]
    setters = _guarded_setters(ir)
    if setters:
        out += ["// Erratum-guarded write paths.", ""] + setters

    return EmittedRust(source="\n".join(out), errata_applied=applied)
